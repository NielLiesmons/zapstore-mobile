/// Renders a single Zaplab-Icons glyph.
///
/// Matches LabIcon from zaplab_design exactly:
/// - No SizedBox/Center wrapper — Stack sizes naturally from Text children
/// - Uses `color:` property for solid fills (not `foreground: Paint()`)
/// - Uses `foreground: Paint()..shader` only for gradient fills
/// - Fill defaults to transparent (Color(0x00000000)) when color==null
///   → stroke-only icons work correctly (pass outlineColor, no color)
/// - Supports `outlineColor` + `outlineThickness` for outlined/stroked icons
class AppIcon extends StatelessWidget {
  const AppIcon(
    this.glyph, {
    super.key,
    this.size = 20.0,
    this.color,
    this.gradient,
    this.outlineColor,
    this.outlineThickness = 0.0,
  });

  final String glyph;
  final double size;
  final Color? color;
  final Gradient? gradient;
  final Color? outlineColor;
  final double outlineThickness;

  @override
  Widget build(BuildContext context) {
    // Transparent spacer — no rendering needed (matches LabIcon early exit)
    if (outlineColor == null &&
        outlineThickness == 0 &&
        gradient == null &&
        color == null) {
      return Text(
        glyph,
        style: const TextStyle(
          fontFamily: 'Zaplab-Icons',
          decoration: TextDecoration.none,
          color: Color(0x00000000),
        ),
      );
    }

    return Stack(
      children: [
        // Outline layer (drawn first, sits behind fill)
        if (outlineColor != null && outlineThickness > 0)
          Text(
            glyph,
            style: TextStyle(
              fontFamily: 'Zaplab-Icons',
              fontSize: size,
              decoration: TextDecoration.none,
              foreground: Paint()
                ..style = PaintingStyle.stroke
                ..strokeWidth = outlineThickness
                ..color = outlineColor!
                ..strokeCap = StrokeCap.round
                ..strokeJoin = StrokeJoin.round,
            ),
          ),
        // Fill layer — gradient uses foreground shader; solid uses color: property
        Text(
          glyph,
          style: TextStyle(
            fontFamily: 'Zaplab-Icons',
            fontSize: size,
            decoration: TextDecoration.none,
            foreground: gradient != null
                ? (Paint()
                  ..shader = gradient!.createShader(
                    Rect.fromLTWH(0, 0, size, size),
                  ))
                : null,
            // When color==null: transparent fill so outline-only icons work
            color: gradient == null ? (color ?? const Color(0x00000000)) : null,
          ),
        ),
      ],
    );
  }
}
